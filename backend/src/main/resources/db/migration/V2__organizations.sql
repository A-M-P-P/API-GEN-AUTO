-- API-GEN-AUTO - organisations
-- Une organisation regroupe zéro ou plusieurs API.
-- Compatible Oracle 12c+ et H2 (mode Oracle).

CREATE TABLE organizations (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    code            VARCHAR(60) NOT NULL,
    name            VARCHAR(150) NOT NULL,
    description     CLOB,
    active          NUMBER(1) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP(6),
    CONSTRAINT pk_organization PRIMARY KEY (id),
    CONSTRAINT ux_organization_code UNIQUE (code)
);

-- Rattachement des API : nullable, une API peut ne dépendir d'aucune organisation.
ALTER TABLE api_definitions ADD organization_id NUMBER(19);

ALTER TABLE api_definitions
    ADD CONSTRAINT fk_api_organization
    FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE SET NULL;

CREATE INDEX idx_api_organization ON api_definitions (organization_id);
